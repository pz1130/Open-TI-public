"""证据包与投诉邮件（设计文档 11、12.1）。证据读出后核对 SHA-256；HTML 快照只以纯文本放入证据包、不随邮件发出。"""

from __future__ import annotations

import hashlib
import io
import json
import re
import zipfile
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime
from email.message import EmailMessage
from typing import Any

from opti.alerting.views import defang
from opti.db.models import Alert, Entity, Evidence, Finding, Takedown
from opti.organization import Organization
from opti.storage.objects import ObjectStore
from opti.takedown.render import defang_url
from opti.takedown.targets import clean_email

MAX_BUNDLE_BYTES = 50 * 1024 * 1024
MAX_EML_SCREENSHOTS = 3
README = (
    "本证据包由 Open-TI 生成。evidence/ 下的 .txt 文件是网页 HTML 快照原文，请勿改名为 .html 在浏览器中打开。\n"
    "SHA256SUMS 列出每个文件的 SHA-256，可用 `sha256sum -c SHA256SUMS` 核对；manifest.json 记录采集时间、节点与方法。\n"
    "分析员上传的截图（kind=upload）已重新编码去除元数据，manifest.json 另记原文件 SHA-256（original_sha256）与上传人。\n\n"
    "This evidence package was generated by Open-TI. The .txt files under evidence/ are raw HTML snapshots;\n"
    "do not open them in a browser. Verify integrity with `sha256sum -c SHA256SUMS`.\n"
    "Analyst-uploaded screenshots (kind=upload) were re-encoded without metadata; manifest.json also records\n"
    "the original file's SHA-256 (original_sha256) and the uploader.\n"
)


class BundleError(Exception):
    def __init__(self, status: int, message: str) -> None:
        super().__init__(message)
        self.status = status
        self.message = message


def _name(ev: Evidence) -> str:
    ext = "png" if ev.content_type == "image/png" else "txt"
    return f"evidence/{ev.id}-{re.sub(r'[^a-zA-Z0-9_-]', '_', ev.kind)}.{ext}"


async def _read(store: ObjectStore, ev: Evidence) -> bytes:
    if ev.size > MAX_BUNDLE_BYTES:
        raise BundleError(413, "evidence is too large")
    data = await store.get(ev.object_key)
    if len(data) > MAX_BUNDLE_BYTES:
        raise BundleError(413, "evidence is too large")
    if hashlib.sha256(data).hexdigest() != ev.sha256:
        raise BundleError(409, f"evidence {ev.id} failed its integrity check")
    return data


def _defanged(entity: Entity) -> str:
    return defang_url(entity.value) if entity.type == "url" else defang(entity.value)


async def evidence_bundle(
    store: ObjectStore,
    *,
    alert: Alert,
    finding: Finding,
    entity: Entity,
    evidence: Sequence[Evidence],
    now: datetime,
    uploaders: Mapping[int, str] | None = None,
) -> bytes:
    """uploaders：上传人用户 ID → 用户名，写入清单保证上传截图的证据链。"""
    names = uploaders or {}
    if sum(ev.size for ev in evidence) > MAX_BUNDLE_BYTES:
        raise BundleError(413, "evidence bundle is too large")
    files: list[tuple[str, bytes]] = []
    total = 0
    for ev in evidence:
        data = await _read(store, ev)
        total += len(data)
        if total > MAX_BUNDLE_BYTES:
            raise BundleError(413, "evidence bundle is too large")
        files.append((_name(ev), data))
    snap = alert.routing if isinstance(alert.routing, dict) else {}
    rdap = (entity.enrichment or {}).get("rdap")
    manifest: dict[str, Any] = {
        "generated_at": now.isoformat(),
        "alert": {
            "id": alert.id, "severity": alert.severity, "status": alert.status,
            "created_at": alert.created_at.isoformat(), "category": snap.get("category") or finding.category,
            "score": snap.get("score", finding.score),
        },
        "finding": {
            "id": finding.id, "category": finding.category, "score": finding.score,
            "first_seen": finding.first_seen.isoformat(), "last_seen": finding.last_seen.isoformat(),
            "sources": list(finding.sources),
        },
        "entity": {"type": entity.type, "value": _defanged(entity), "defanged": _defanged(entity)},
        "registration": rdap.get("data") if isinstance(rdap, dict) else None,
        "evidence": [
            {
                "file": name, "id": ev.id, "kind": ev.kind, "content_type": ev.content_type,
                "sha256": ev.sha256, "size": ev.size, "captured_at": ev.captured_at.isoformat(),
                "node_id": ev.node_id, "method": ev.method,
                "source_url": defang_url(ev.source_url) if ev.source_url else None,
                "uploaded_by": names.get(ev.uploaded_by) if ev.uploaded_by is not None else None,
                "original_sha256": ev.original_sha256,
            }
            for ev, (name, _) in zip(evidence, files, strict=True)
        ],
    }  # fmt: skip
    buf = io.BytesIO()
    stamp = now.astimezone(UTC).timetuple()[:6]
    with zipfile.ZipFile(buf, "w") as zf:

        def put(name: str, data: bytes) -> None:
            zf.writestr(
                zipfile.ZipInfo(name, date_time=stamp), data, compress_type=zipfile.ZIP_DEFLATED
            )

        put("README.txt", README.encode())
        put("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2).encode())
        for name, data in files:
            put(name, data)
        sums = "".join(f"{hashlib.sha256(data).hexdigest()}  {name}\n" for name, data in files)
        put("SHA256SUMS", sums.encode())
    return buf.getvalue()


async def build_eml(
    store: ObjectStore | None, org: Organization, td: Takedown, evidence: Sequence[Evidence]
) -> bytes:
    """待发送的投诉邮件：X-Unsent 让 Outlook 打开为草稿，由使用机构自己的邮箱发出（平台不发送）。"""
    to = clean_email(td.target.get("email"))
    if to is None:
        raise BundleError(409, "this target has no e-mail address; use its web form instead")
    msg = EmailMessage()
    sender = clean_email(org.takedown_sender)
    if sender:
        msg["From"] = sender
    msg["To"] = to
    msg["Subject"] = td.subject
    msg["X-Unsent"] = "1"
    msg.set_content(td.body)
    shots = [ev for ev in evidence if ev.content_type == "image/png"][:MAX_EML_SCREENSHOTS]
    total = 0
    if sum(ev.size for ev in shots) > MAX_BUNDLE_BYTES:
        raise BundleError(413, "mail attachments are too large")
    if store is not None:
        for ev in shots:
            data = await _read(store, ev)
            total += len(data)
            if total > MAX_BUNDLE_BYTES:
                raise BundleError(413, "mail attachments are too large")
            msg.add_attachment(
                data, maintype="image", subtype="png", filename=f"evidence-{ev.id}.png"
            )
    return msg.as_bytes()
